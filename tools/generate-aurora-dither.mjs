/** Bake the same spherical square emitters for browsers without WebGL. */
import {writeFileSync} from 'node:fs';
import {AURORA_GRID as grid,sampleAurora} from '../js/scene/aurora-style.js';

const width=4096,height=2048;
const direction=(face,sign,x,y)=>{
 const u=x/grid*2-1,v=y/grid*2-1;
 const p=face===0?[sign,v,u]:face===1?[u,sign,v]:[u,v,sign];
 const length=Math.hypot(...p);return p.map(n=>n/length);
};
const bayer2=(x,y)=>2*(x%2)+3*(y%2)-4*(x%2)*(y%2);
const smooth=(a,b,v)=>{const t=Math.max(0,Math.min(1,(v-a)/(b-a)));return t*t*(3-2*t)};
const groups=new Map();
for(let face=0;face<3;face++)for(const sign of [-1,1]){
 for(let y=0;y<grid;y++)for(let x=0;x<grid;x++){
  const d=direction(face,sign,x+.5,y+.5),light=sampleAurora(d);
  const threshold=(4*bayer2(x,y)+bayer2(Math.floor(x/2),Math.floor(y/2))+.5)/16;
  const ink=smooth(threshold-.035,threshold+.035,light.density);
  if(ink<.08)continue;
  const size=.14+.34*smooth(.05,.94,light.density);
  const center=(Math.atan2(d[2],d[0])/(2*Math.PI)+.5)*width;
  const points=[[-1,-1],[1,-1],[1,1],[-1,1]].map(([dx,dy])=>{
   const p=direction(face,sign,x+.5+dx*size,y+.5+dy*size);
   let px=(Math.atan2(p[2],p[0])/(2*Math.PI)+.5)*width;
   if(px-center>width/2)px-=width;if(px-center<-width/2)px+=width;
   return [px,(.5-Math.asin(p[1])/Math.PI)*height];
  });
  const color='#'+light.color.map(v=>{
   // Palette quantization keeps the fallback compact and deliberately pixel-like.
   const value=Math.min(255,Math.round(v*ink*(.58+.42*Math.sqrt(light.density))*255/8)*8);
   return value.toString(16).padStart(2,'0');
  }).join('');
  if(!groups.has(color))groups.set(color,[]);
  const paths=groups.get(color);
  for(const shift of [-width,0,width]){
   if(points.every(p=>p[0]+shift<0)||points.every(p=>p[0]+shift>width))continue;
   paths.push('M'+points.map(p=>`${(p[0]+shift).toFixed(1)},${p[1].toFixed(1)}`).join('L')+'Z');
  }
 }
}
const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
<!-- Generated by tools/generate-aurora-dither.mjs from the dome's light field. -->
<rect width="${width}" height="${height}" fill="#000102"/>
${[...groups].map(([color,paths])=>`<path fill="${color}" d="${paths.join('')}"/>`).join('\n')}
</svg>\n`;
writeFileSync(new URL('../assets/aurora-dither.svg',import.meta.url),svg);
console.log(`Generated dithered aurora (${Math.round(svg.length/1024)} KB).`);
