/** Static, fine-tile fallback for devices without WebGL. No simulated color fade. */
import {writeFileSync} from 'node:fs';

const width=4096,height=2048,columns=180,rows=90;
const tileWidth=width/columns,tileHeight=height/rows,gap=.4;
const clamp=x=>Math.max(0,Math.min(1,x));
const smooth=(a,b,x)=>{const t=clamp((x-a)/(b-a));return t*t*(3-2*t)};
const dot=(a,b)=>a.reduce((sum,v,i)=>sum+v*b[i],0);
const normalized=v=>{const n=Math.hypot(...v);return v.map(x=>x/n)};
const falloff=(d,w)=>2**(-d*d/(w*w));
const mix=(a,b,t)=>a.map((v,i)=>v+(b[i]-v)*t);
const panels=[];
for(let row=0;row<rows;row++)for(let col=0;col<columns;col++){
 const longitude=((col+.5)/columns-.5)*Math.PI*2,latitude=(.5-(row+.5)/rows)*Math.PI;
 const p=[Math.cos(latitude)*Math.cos(longitude),Math.sin(latitude),Math.cos(latitude)*Math.sin(longitude)];
 const wave=.045*Math.sin(dot(p,[3,2,4]))+.025*Math.sin(dot(p,[-5,1,2]));
 const arc=dot(p,normalized([-.15,1,-.22]))-.24+wave;
 const crossing=dot(p,normalized([-.4,.8,-.44]))-.36-wave*.8;
 const crown=dot(p,normalized([.16,.95,-.28]))-.68+wave*.6;
 const core=falloff(arc,.023)*.73+falloff(crossing,.026)*.46+falloff(crown,.022)*.38;
 const veil=falloff(arc-.036,.062)*.32+falloff(crossing-.03,.065)*.18+falloff(crown-.025,.05)*.14;
 const hue=.5+.5*Math.sin(dot(p,[2,1.3,-1.7])-1.1),upper=smooth(-.32,.12,p[1]);
 let tint=mix([.98,.075,.19],[.6,.12,.94],smooth(.08,.52,hue));
 tint=mix(tint,[.08,.46,1],smooth(.52,.94,hue));
 const base=mix([.006,.011,.025],[.015,.025,.048],p[1]*.5+.5);
 const color=base.map((v,i)=>Math.round(clamp(v+tint[i]*(core+veil)*upper*.78)*255).toString(16).padStart(2,'0')).join('');
 panels.push(`<rect x="${(col*tileWidth+gap/2).toFixed(2)}" y="${(row*tileHeight+gap/2).toFixed(2)}" width="${(tileWidth-gap).toFixed(2)}" height="${(tileHeight-gap).toFixed(2)}" fill="#${color}"/>`);
}
writeFileSync(new URL('../assets/aurora-panels.svg',import.meta.url),`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
<!-- Generated by tools/generate-aurora-panorama.mjs: static no-WebGL approximation. -->
<path fill="#030713" d="M0 0H4096V2048H0z"/>
${panels.join('\n')}
</svg>\n`);
console.log(`Generated ${panels.length} fallback panels.`);
