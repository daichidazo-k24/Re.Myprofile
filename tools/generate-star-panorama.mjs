import {writeFileSync} from 'node:fs';
import {createPlanetariumStars} from '../js/scene/planetarium-model.js';

const width=4096,height=2048;
const groups=new Map();
for(const star of createPlanetariumStars()){
 const [x,y,z]=star.direction,latitude=Math.asin(y);
 const cx=(Math.atan2(z,x)/(2*Math.PI)+.5)*width,cy=(.5-latitude/Math.PI)*height;
 const ry=star.radius*.68,rx=ry/Math.max(.04,Math.cos(latitude));
 const color=star.color.map(v=>Math.round(v*255).toString(16).padStart(2,'0')).join('');
 if(!groups.has(color))groups.set(color,[]);
 const shapes=groups.get(color);
 for(const offset of [-width,0,width]){
  if(cx+offset+rx<0||cx+offset-rx>width)continue;
  shapes.push(`<ellipse cx="${(cx+offset).toFixed(2)}" cy="${cy.toFixed(2)}" rx="${rx.toFixed(2)}" ry="${ry.toFixed(2)}" opacity="${star.brightness.toFixed(2)}"/>`);
 }
}
const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
<!-- Generated by tools/generate-star-panorama.mjs; illustrative star positions. -->
${[...groups].map(([color,shapes])=>`<g fill="#${color}">\n${shapes.join('\n')}\n</g>`).join('\n')}
</svg>\n`;
writeFileSync(new URL('../assets/planetarium-stars.svg',import.meta.url),svg);
console.log(`Generated ${createPlanetariumStars().length} stars (${Math.round(svg.length/1024)} KB).`);
